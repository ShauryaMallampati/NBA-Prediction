
import json

def json_to_netscape(json_path, output_path):
    try:
        with open(json_path, 'r') as f:
            cookies = json.load(f)
    except json.JSONDecodeError:
        print("❌ Error: cookies.json is not valid JSON")
        return
    
    count = 0
    with open(output_path, 'w') as f:
        f.write("# Netscape HTTP Cookie File\n")
        f.write("# This file is generated by a script\n\n")
        
        for cookie in cookies:
            domain = cookie.get('domain', '')
            if 'youtube' not in domain and 'google' not in domain:
                continue
                
            # Initial dot means include subdomains
            flag = 'TRUE' if domain.startswith('.') else 'FALSE'
            path = cookie.get('path', '/')
            secure = 'TRUE' if cookie.get('secure', False) else 'FALSE'
            expiration = str(int(cookie.get('expirationDate', 0)))
            name = cookie.get('name', '')
            value = cookie.get('value', '')
            
            f.write(f"{domain}\t{flag}\t{path}\t{secure}\t{expiration}\t{name}\t{value}\n")
            count += 1
            
    print(f"✅ Converted {count} relevant cookies to {output_path}")

if __name__ == "__main__":
    json_to_netscape('cookies.json', 'cookies.txt')
